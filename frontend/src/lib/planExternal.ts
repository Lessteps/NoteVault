// Mentor — «Crear el plan con otra IA» (Antigravity, un chat, Gemini CLI…): el MISMO pedido que la app le haría a su propia IA (reglas del Mentor +
// precondiciones fijas + catálogo real de temas) escrito en un archivo Markdown. La otra IA lo lee SIN la app abierta y escribe el plan en un archivo al
// lado; la app lo valida con el mismo analizador de siempre (solo temas del catálogo, precondiciones intactas) y lo crea como plan «propuesto».
// No hace falta clave de API ni modelo local. Puro: no toca disco ni red.

export interface ExternalPlanDocInput {
  /** reglas del Mentor + informe + catálogo + precondiciones fijas (el system del pedido normal) */
  system: string;
  /** la petición en una frase («Quiero un plan del … al …») */
  request: string;
  /** ruta ABSOLUTA donde la otra IA escribe su respuesta */
  answerAbs: string;
  today: string;
  /** cuántos temas tiene el catálogo del pedido */
  topics: number;
}

export function buildExternalPlanDoc(i: ExternalPlanDocInput): string {
  return [
    "# Create a study plan for NoteVault",
    "",
    `Generated by the NoteVault Mentor on ${i.today}. ${i.topics} topics are available in the catalog below.`,
    "",
    "You are replacing the Mentor's built-in AI for one task: **design the study plan** described below. NoteVault will validate your answer, so follow the rules exactly.",
    "",
    "## How to answer (binding)",
    "",
    `1. Write your answer to this file: \`${i.answerAbs}\``,
    "2. The file must contain **one JSON object** (`\"type\": \"plan_draft\"`) with the exact structure the instructions below describe. Nothing else: no commentary, no extra files.",
    "3. Choose and order topics **only from the catalog** (use each `folder` exactly as written). Topics you invent are discarded by the app.",
    "4. The preconditions (dates, daily time, study days, pace) are fixed facts. Do not change them: the app ignores any value you return for them.",
    "5. If you cannot write files, reply in the chat with the JSON object alone inside a ```json block; the person will paste it into NoteVault.",
    "6. Do not modify the NoteVault app, the vault or any setting. Reading files is all you need.",
    "",
    "## Instructions of the Mentor (Spanish; keep the JSON keys exactly as they are)",
    "",
    i.system.trim(),
    "",
    "## The request",
    "",
    i.request.trim(),
    "",
  ].join("\n");
}

/** La frase corta que se pega en la otra IA (conversación nueva). */
export function externalPlanShortPrompt(file: string, answerAbs: string): string {
  return `NEW TASK — ignore everything we discussed before in this conversation. Read \`${file}\` completely: it asks you to design a study plan for NoteVault. Do exactly what it says and write the answer to \`${answerAbs}\`. Do NOT modify the NoteVault app, the vault or any setting, and do not run commands other than reading files.`;
}

/** Texto para pegar en una IA que NO puede leer archivos (un chat web): el documento entero y la respuesta va en el chat. */
export function externalPlanChatPrompt(doc: string): string {
  return `${doc}\n\n---\nReply with the JSON object alone inside a \`\`\`json block (you cannot write files in this conversation).`;
}
