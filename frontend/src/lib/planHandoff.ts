// Mentor — «Plan para otra IA»: convierte el informe de «Ejecutar plan» (lo que falta crear) en un documento Markdown, en inglés y muy concreto,
// que se le entrega a otra IA (Antigravity, Gemini CLI, Codex…) para que genere lo que falta: notas de teoría, canvas, manifiestos
// `.practica.md` y ejercicios. Es PURO: no toca disco ni la IA de la app; solo formatea. El que lo escribe en la vault es la API.
//
// Qué NO va a la otra IA: las carpetas y katas de `programming_practice` (las crea la app sin IA al ejecutar el plan) ni los defectos de
// notas que ya existen (se revisan a mano). Se listan aparte para que no los toque.

import { KIND_LABEL, type ExecTask, type ExecutionReport, type TaskKind } from "./planExecution.js";

export interface HandoffMeta {
  planName: string;
  start: string;
  end: string;
  /** rutas (relativas a la vault) de los documentos-contrato que EXISTEN y debe leer primero */
  contracts: string[];
  /** hay herramientas de verificación `tools/programming_kb` (solo el espacio Programación) y desde qué carpeta se ejecutan */
  toolsDir?: string;
}

/** Tareas que sí hace la otra IA, en el orden en que el informe las ejecutaría. */
const AI_KINDS: readonly TaskKind[] = ["topic_new", "theory", "canvas", "manifest", "practice"];
const isAiTask = (t: ExecTask): boolean => AI_KINDS.includes(t.kind);

const cellsOf = (t: ExecTask): Array<{ skill: string; difficulty: number }> => {
  const raw = t.args?.cells;
  return Array.isArray(raw) ? raw.filter((c): c is { skill: string; difficulty: number } => !!c && typeof c.skill === "string" && Number.isFinite(c.difficulty)) : [];
};

const bySkill = (cells: Array<{ skill: string; difficulty: number }>): string =>
  [...new Set(cells.map((c) => c.skill))].map((s) => `${s} (d${cells.filter((c) => c.skill === s).map((c) => c.difficulty).sort().join(", d")})`).join("; ");

const esc = (s: string): string => s.replace(/\|/g, "\\|");

export function buildHandoffMarkdown(report: ExecutionReport, meta: HandoffMeta): string {
  const aiTasks = report.tasks.filter(isAiTask);
  const count = (k: TaskKind): number => aiTasks.filter((t) => t.kind === k).length;
  const practice = aiTasks.filter((t) => t.kind === "practice");
  const knownCells = practice.reduce((n, t) => n + cellsOf(t).length, 0);
  const unknownPractice = practice.filter((t) => t.args?.unknown === true).length;
  const appOnly = report.tasks.filter((t) => !isAiTask(t));
  const L: string[] = [];
  const push = (...x: string[]): void => void L.push(...x);

  push(
    `# Handoff plan — ${meta.planName}`,
    "",
    `Plan period: ${meta.start} → ${meta.end}. Generated by the NoteVault Mentor on ${report.at.slice(0, 16).replace("T", " ")}. ` +
      `Scope: ${report.scope.mode === "all" ? "the whole plan" : report.scope.mode === "weeks" ? `weeks ${report.scope.fromWeek}–${report.scope.toWeek}` : `area "${report.scope.areaKey}"`}` +
      `${report.scope.includeRecommended ? ", including the recommended difficulty ladder" : ", required items only"}.`,
    "",
    "To start or resume in any session, paste only this:",
    "",
    "> Read this file completely and execute it. Work through section 4 in order, ticking each box (`- [x]`) in THIS file when the item",
    "> passes its check. The Mentor recounts what is missing from the vault, so the checkboxes are only your own progress marker.",
    "",
    "Everything you write is in **English** unless the existing notes of that area are in another language (then match them).",
    "Quality beats speed: **every code block must be correct, and correctness is verified by running it, never by reasoning.**",
    "",
    "## 1. Read first (binding contracts)",
    "",
  );
  if (meta.contracts.length) meta.contracts.forEach((c, i) => push(`${i + 1}. \`${c}\``));
  else push("No contract documents were found in this vault. Open one finished topic of the same area (note, map, `.practica.md`, one exercise) and copy its structure exactly.");
  push(
    "",
    "Use a **finished topic of the same area as the quality bar** (its theory note, its `.practica.md` and one exercise) and match its structure, length and tone.",
    "",
    "## 2. What is missing (explicit extension — the numbers you must hit)",
    "",
    "| Deliverable | Items | Notes |",
    "|---|---|---|",
    `| New topics (folder + theory + manifest) | ${count("topic_new")} | the folder does not exist yet |`,
    `| Theory notes (and their map) | ${count("theory")} | the topic folder exists, the note does not |`,
    `| Topic maps (canvas) only | ${count("canvas")} | note exists, map missing: generate it, never draw it |`,
    `| Practice manifests (\`<topic>.practica.md\`) | ${count("manifest")} | decides the skills of the topic |`,
    `| Topics needing exercises | ${practice.length} | ${knownCells} known cells (skill × difficulty)${unknownPractice ? `; ${unknownPractice} topics get their skills only after their manifest exists` : ""} |`,
    "",
    `Estimated size: ~${aiTasks.reduce((n, t) => n + t.files, 0)} files. A **cell** is (topic, skill, difficulty): write **one exercise per cell** (more only if the item says so).`,
    "",
    "## 3. Per-artifact rules",
    "",
    "| Artifact | Path (inside the topic folder) | Rule |",
    "|---|---|---|",
    "| Theory note | `<topic>.md` | the heading contract of the area's theory-note skill; one idea per topic; link other topics with `[[exact folder name]]` |",
    "| Topic map | `<topic> — mapa.canvas` | **generated** from the note by the area's generator/finalize tool; never edited by hand |",
    "| Manifest | `<topic>.practica.md` | frontmatter `type: practica`, `subject`, `title`, `topic_type`, `skills: [...]`, `min_per_skill`, `target_difficulty`, `exam`; copy a finished one |",
    "| Exercise | `Ejercicios/<skill>/ej_<skill>_d<difficulty>_<batch>_<n>.md` | frontmatter `type: exercise`, `subject`, `title`, `mode` (= the skill = the sub-folder), `difficulty`, `assistance: nohelp`, `topic` (exact folder name); sections `## Statement`, `## Hints`, `## Solution`, `## Rubric` (≥ 3 checkable items) |",
    "",
    "`<batch>` is any integer of 6+ digits, the same for the files of one cell written together; `<n>` counts 1, 2, 3 inside the batch.",
    "Never overwrite or delete an existing file. If a file exists, skip that item and say so in your report.",
    "",
  );
  if (meta.toolsDir) {
    push(
      "### Verification tools (run from `" + meta.toolsDir + "`)",
      "",
      "```",
      "node tools/programming_kb/status.mjs                      # theory notes and maps per area",
      "node tools/programming_kb/exercises_status.mjs --next 8   # next topics with missing exercise cells",
      "node tools/programming_kb/check_examples.mjs \"^<n>\\.<m> \"   # runs every code Case of a note and prints the real output",
      "node tools/programming_kb/finalize.mjs \"^<n>\\.<m> \"        # adds frontmatter and GENERATES the map",
      "node tools/programming_kb/exercises_check.mjs \"^<n>\\.<m> \"  # validates exercise files; exit 1 on any failure",
      "node tools/programming_kb/links.mjs \"^<n>\\.\"               # [[links]] that are not an exact folder name",
      "```",
      "",
    );
  }
  push("## 4. Work list (in this order; weeks are the plan's target weeks)", "");
  for (const a of report.areas) {
    const topics = a.topics.filter((t) => t.tasks.some(isAiTask));
    const extra = a.areaTasks.filter((t) => t.kind === "topic_new" && isAiTask(t));
    if (!topics.length && !extra.length) continue;
    push(`### ${esc(a.area)}`, "");
    for (const t of topics) {
      const tasks = t.tasks.filter(isAiTask);
      push(`- [ ] \`${t.folder}\` — week ${t.week}, design score ${Math.round(t.score)}%`);
      for (const k of tasks) {
        const cells = cellsOf(k);
        const detail =
          k.kind === "practice"
            ? cells.length
              ? `exercises for: ${bySkill(cells)}`
              : "exercises for every skill of the manifest you create above (≥ 1 per skill at difficulty 1)"
            : k.kind === "topic_new"
              ? "create the topic folder, the theory note, the manifest, then generate the map"
              : k.kind === "theory"
                ? "write the theory note, then generate its map"
                : k.kind === "canvas"
                  ? "generate the topic map from the existing note"
                  : "write the manifest";
        push(`  - ${KIND_LABEL[k.kind]}${k.required ? "" : " (recommended)"}: ${detail}`);
      }
    }
    for (const k of extra) push(`- [ ] **New topic proposed by the review:** ${esc(k.title)} — create it in this area (folder, note, manifest, map)`);
    push("");
  }
  if (!report.areas.some((a) => a.topics.some((t) => t.tasks.some(isAiTask)))) push("_Nothing to create with this scope._", "");

  push("## 5. Rules and traps", "");
  push(
    "- **Never invent** an API, flag, option, version or number. If you are not certain it exists, do not use it. Run it and paste the real output.",
    "- One topic = one idea. What belongs to another topic is **linked**, not repeated. Realistic context (invoices, bookings, tickets); no `foo`/`bar`.",
    "- The exercises of one cell must differ in scenario **and** angle; do not copy the theory note's own examples.",
    "- Commands in exercises must be safe (no `rm -rf`, no network installs). Do not use real keys, endpoints or personal data.",
    "- Do not touch: other topics' finished files, `.notevault/`, the app source, `programming_practice/` (the app creates it), or any existing `.canvas`.",
    "- If another agent edited a file you are about to change, re-read it first and keep its changes.",
    "",
  );

  if (appOnly.length) {
    push("## 6. NOT for you (the app creates these without AI)", "");
    const kinds = [...new Set(appOnly.map((t) => KIND_LABEL[t.kind]))];
    push(`${appOnly.length} items: ${kinds.join("; ")}. They are made by the Mentor's «Ejecutar plan» in NoteVault. Do not create them by hand.`, "");
  }
  if (report.manual.length) {
    push("## 7. Existing notes with defects (do NOT rewrite; list them in your final report)", "");
    for (const m of report.manual) push(`- \`${m.folder}\`: ${esc(m.gaps.join("; "))}`);
    push("");
  }
  const proposals = report.areas.flatMap((a) => a.proposals.filter((p) => !p.included).map((p) => ({ area: a.area, ...p })));
  if (proposals.length) {
    push("## 8. Topics the review proposed (NOT included; only create if the user says so)", "");
    for (const p of proposals) push(`- ${esc(p.area)}: **${esc(p.title)}** — ${esc(p.why)}`);
    push("");
  }

  push(
    "## 9. Done definition and handoff to the user",
    "",
    "1. Every box in section 4 is ticked and its check passed (`finalize` → `BLOCKED 0`, `links` → 0 unresolved, `exercises_check` → exit 0 where the tools exist).",
    "2. Commit what you created (a normal commit; `.canvas` files may be git-ignored on purpose).",
    "3. Tell the user: *open NoteVault → Mentor → Plan → «Ejecutar plan» → «Analizar el plan»*: the report recounts what is still missing.",
    "4. If you stop early, say which area and topic you stopped at, so the next session resumes from the first unticked box.",
    "",
  );
  return L.join("\n");
}
